"""Read documents from downloaded raw files (parquet, json.gz or jsonl) with light filtering."""
from __future__ import annotations

import gzip
import json
import os
import re
from typing import Iterator

import pyarrow.parquet as pq

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
RAW = os.path.join(ROOT, "data", "raw")
# Greek, Cyrillic, Armenian, Hebrew, Arabic, Indic, ..., CJK, Hangul, full-width forms. Latin (incl. accents),
# punctuation, arrows, math operators, box drawing and emoji do not count.
NON_LATIN = re.compile(r"[\u0370-\u1fff\u2e80-\uffff]")


def source_files(src, raw_root: str = RAW) -> list[str]:
    """Finished files of a source, in registry order (partial downloads live under .cache/)."""
    paths = [os.path.join(raw_root, src.name, f) for f in src.files]
    return [p for p in paths if os.path.exists(p)]


def _code_ok(text: str, max_line: int = 1000, max_chars: int = 200_000) -> bool:
    if len(text) > max_chars:
        return False                      # data blobs, generated tables
    return max(map(len, text.split("\n"))) <= max_line   # minified / base64 files


def iter_file_docs(path: str, src, min_chars: int = 32, max_chars: int | None = None,
                   batch_size: int = 1024, stream: bool = False) -> Iterator[str]:
    keep = set(src.keep_langs) if src.keep_langs else None
    is_code = src.kind == "code"

    def emit(t):
        if not t or len(t) < min_chars:
            return None
        if is_code and not _code_ok(t):
            return None
        if src.max_non_latin and len(NON_LATIN.findall(t)) > src.max_non_latin * len(t):
            return None                   # mostly non-English comments / strings
        return t if max_chars is None else t[:max_chars]

    if path.endswith(".parquet"):
        # stream: no pre-buffering, a small read buffer, one thread (PG19: peak ~0.9 GB instead of ~1.1 GB per file)
        pf = pq.ParquetFile(path, pre_buffer=False, buffer_size=4 << 20) if stream else pq.ParquetFile(path)
        cols = [src.text_field] + (["language"] if keep else [])
        for b in pf.iter_batches(columns=cols, batch_size=batch_size, use_threads=not stream):
            texts = b.column(src.text_field).to_pylist()
            langs = b.column("language").to_pylist() if keep else None
            for i, t in enumerate(texts):
                if keep is not None and langs[i] not in keep:
                    continue
                t = emit(t)
                if t is not None:
                    yield t
    elif path.endswith((".json.gz", ".jsonl.gz", ".jsonl", ".json")):
        opener = gzip.open if path.endswith(".gz") else open
        with opener(path, "rt", encoding="utf-8") as fh:
            for line in fh:
                if not line.strip():
                    continue
                rec = json.loads(line)
                if rec.get("autogenerated"):
                    continue
                if src.min_score and (rec.get("int_score") or 0) < src.min_score:
                    continue          # Stack-Edu: below the educational-score threshold
                if keep is not None:
                    meta = rec.get("metadata") if isinstance(rec.get("metadata"), dict) else {}
                    if (rec.get("language") or rec.get("lang") or meta.get("language")) not in keep:
                        continue
                t = emit(rec.get(src.text_field))
                if t is not None:
                    yield t
    else:
        raise ValueError(f"unsupported file type: {path}")


def iter_source_docs(src, raw_root: str = RAW, **kw) -> Iterator[str]:
    for p in source_files(src, raw_root):
        yield from iter_file_docs(p, src, **kw)
